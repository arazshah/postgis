from dataclasses import dataclass, field


@dataclass(frozen=True)
class Guide:
    slug: str
    title: str
    summary: str
    icon: str
    seconds: int = 0  # مدت ویدیو
    steps: tuple = ()  # (عنوان، توضیح)
    tips: tuple = ()
    related: tuple = ()  # (slug آموزش، عنوان)
    faq: tuple = ()  # (پرسش، پاسخ)
    group: str = "شروع کار"
    extra: dict = field(default_factory=dict)

    @property
    def duration(self) -> str:
        """۱:۰۵"""
        s = f"{self.seconds // 60}:{self.seconds % 60:02d}"
        return s.translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))

    @property
    def iso_duration(self) -> str:
        return f"PT{self.seconds // 60}M{self.seconds % 60}S"

    @property
    def video(self) -> str:
        return f"help/video/{self.slug}.mp4"

    @property
    def poster(self) -> str:
        return f"help/video/{self.slug}.jpg"


