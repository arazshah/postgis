"""قابلیت‌های مشترک به‌صورت **پلاگین مستقل** (ADR-0009): هر قابلیت یک پلاگین با روشن/خاموش، مجوز و قیمت جدا در «پلاگین‌ها».

پلاگین‌های قابلیت (شناسه‌ها `cap_*`) کد جدا ندارند؛ هسته منطق را دارد و هر نقطه‌ی ورود با `caps.allowed(...)` سنجیده می‌شود.
بدون ردیف وضعیت باز هستند (رفتار قبلی)؛ مدیر می‌تواند خاموش، به دارندگان مجوز محدود یا (از «پلاگین‌ها») برای فروش آگهی کند.
"""
from __future__ import annotations

from . import entitlements
from .plugins import registry

CAPS = {
    "notify": ("کانال‌های هشدار پیام‌رسان", "هشدار در بله و تلگرام (با پشتیبان پیامک/ایمیل)، ساعت سکوت و پیوند حساب."),
    "sources": ("منابع بیرونی (ورود دوره‌ای از API)", "واکشی دوره‌ای داده از سرویس‌های بیرونی مثل هواشناسی با فهرست سفید میزبان."),
    "draw": ("ترسیم روی نقشه و ویرایش ردیف", "فیلد هندسه با ترسیم چندضلعی/خط/نقطه و ویرایش و حذف ردیف در صفحه‌ی پلاگین."),
    "reports": ("گزارش PDF و چیدمان قابل‌ویرایش", "گزارش PDF/تصویر از صفحه با ویرایشگر چیدمان (لوگو، متن، نقشه)."),
    "geocoder": ("ژئوکدر فارسی", "تبدیل نشانی فارسی به مختصات روی داده‌ی OSM پایگاه (آزمایشی)."),
}


def pid(cap: str) -> str:
    return f"cap_{cap}"


def register_all() -> None:
    for cap, (name, desc) in CAPS.items():
        if pid(cap) not in registry.plugins:
            registry.register(pid(cap), name, kind="feature", description=desc)


def allowed(cap: str, *, user=None, ws=None) -> bool:
    """قابلیت برای این کاربر/پایگاه در دسترس است؟ (روشن بودن و مجوز پلاگین `cap_*`)."""
    return entitlements.allowed(pid(cap), user=user, ws=ws)
