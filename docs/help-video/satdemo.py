"""داده‌ی نمایشی ماهواره (ویدیوی راهنمای «تصویر ماهواره‌ای»): ۱۲ قطعه‌ی زمین در دشت ورامین و سری زمانی ساختگی NDVI.
فقط برای ضبط رابط؛ اعداد واقعی نیستند."""
LON0, LAT0 = 51.620, 35.300
DX, DY, GAP_X, GAP_Y = 0.0068, 0.0054, 0.0008, 0.0006
# ناحیه‌ی تصویرهای ساختگی (کمی بزرگ‌تر از قطعه‌ها)
SCENE_BBOX = (51.600, 35.283, 51.665, 35.328)
DATES = ["2026-07-12", "2026-07-28", "2026-08-13", "2026-08-29", "2026-09-14", "2026-09-30", "2026-10-16", "2026-11-01"]
CLOUD = [2.1, 5.4, 0.8, 3.3, 1.2, 4.0, 2.6, 1.9]
CURVE = [0.30, 0.45, 0.60, 0.68, 0.66, 0.60, 0.58, 0.57]       # سبزی میانگین در طول فصل
FACTOR = [1.00, 0.92, 1.05, 0.88, 1.08, 0.95, 1.02, 0.80, 0.97, 1.06, 0.90, 1.01]
# قطعه‌هایی که در آخرین تصویر افت می‌کنند (برای نمایش هشدار پایش): شماره‌ی قطعه ← ضریب آخرین تاریخ
DROP = {7: 0.62, 11: 0.66, 3: 0.78}


def parcels():
    out = []
    for i in range(12):
        r, c = divmod(i, 4)
        x, y = LON0 + c * (DX + GAP_X), LAT0 + r * (DY + GAP_Y)
        out.append((f"P{i + 1:02d}", f"قطعه {i + 1}", [[x, y], [x + DX, y], [x + DX, y + DY], [x, y + DY], [x, y]]))
    return out


def ndvi(i: int, t: int) -> float:
    """NDVI قطعه‌ی i (۰ تا ۱۱) در تاریخ t."""
    v = CURVE[t] * FACTOR[i]
    if t == len(DATES) - 1 and (i + 1) in DROP:
        v = CURVE[t - 1] * FACTOR[i] * DROP[i + 1]
    return max(0.05, min(v, 0.9))
